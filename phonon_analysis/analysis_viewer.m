function analysis_viewer()
%% ANALYSIS_VIEWER Interactive viewer for phonon analysis results
%
% Provides a file tree interface to browse analysis results with:
% - Left panel: File tree navigation
% - Center panel: Plot display (both .fig and .png)
% - Right panel: Description of analysis type, expected results, filepath
%
% Usage:
%   analysis_viewer
%
% Author: Gerbode Lab
% Date: 2026

%% ==================== CONFIGURATION ====================
% Default analysis output folder
