    'BackgroundColor', [0.3 0.3 0.4]);

% Tree view
tree = uitree(pnl_tree, 'Position', [8 8 260 810], ...
    'BackgroundColor', [0.15 0.15 0.15], 'FontColor', 'w');

% ---- Center panel: Plot display ----
pnl_plot = uipanel(fig, 'Title', 'Plot', ...
    'Position', [296 8 900 884], ...
    'BackgroundColor', [0.1 0.1 0.1], 'ForegroundColor', 'w');

% Filepath display
uilabel(pnl_plot, 'Text', 'File:', 'Position', [8 852 30 20], 'FontColor', 'w');
ef_filepath = uieditfield(pnl_plot, 'Value', '', ...
    'Position', [40 852 800 22], 'Editable', 'off', ...
    'BackgroundColor', [0.2 0.2 0.2], 'FontColor', 'cyan');
btn_copy = uibutton(pnl_plot, 'Text', 'Copy', 'Position', [845 852 45 22], ...
    'BackgroundColor', [0.3 0.4 0.3]);

% Plot axes
ax_plot = uiaxes(pnl_plot, 'Position', [8 8 880 835], ...
    'Color', 'k', 'XColor', 'w', 'YColor', 'w');

% ---- Right panel: Description ----
pnl_desc = uipanel(fig, 'Title', 'Analysis Info', ...
    'Position', [1204 8 388 884], ...
    'BackgroundColor', [0.2 0.2 0.2], 'ForegroundColor', 'w');

% Analysis name
uilabel(pnl_desc, 'Text', 'Analysis Type:', 'Position', [8 850 100 18], ...
    'FontColor', 'w', 'FontWeight', 'bold');
lbl_analysis_name = uilabel(pnl_desc, 'Text', '-', ...
    'Position', [8 825 370 22], 'FontColor', 'cyan', 'FontSize', 14);

% Description text area
uilabel(pnl_desc, 'Text', 'Description:', 'Position', [8 795 100 18], ...
    'FontColor', 'w', 'FontWeight', 'bold');
