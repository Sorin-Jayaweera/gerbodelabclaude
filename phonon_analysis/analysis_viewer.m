uilabel(pnl_desc, 'Text', 'Theory / Expected:', 'Position', [8 560 120 18], ...
    'FontColor', 'w', 'FontWeight', 'bold');
txt_theory = uitextarea(pnl_desc, 'Position', [8 355 370 200], ...
